import sys, unicodedata
path, out = sys.argv[1], sys.argv[2]
bad = set()
def scriptish(cp):
    c = chr(cp)
    if '0' <= c <= '9': return True
    try: n = unicodedata.name(c)
    except ValueError: return False
    return n.startswith(('LATIN','GREEK','CYRILLIC','DIGIT')) or (0x20 < cp < 0x7f)
version = ''
for line in open(path, encoding='utf-8-sig'):
    if line.startswith('# Version'): version = line.strip('# \n')
    line = line.split('#')[0].strip()
    if not line: continue
    src, tgt, *_ = [f.strip() for f in line.split(';')]
    if len(src.split()) != 1: continue
    if any(scriptish(int(t, 16)) for t in tgt.split()):
        bad.add(int(src, 16))
def pool(ranges):
    return [cp for a, b in ranges for cp in range(a, b+1)
            if unicodedata.category(chr(cp)).startswith('L') and cp not in bad]
cher = pool([(0x13A0,0x13F5),(0x13F8,0x13FD),(0xAB70,0xABBF)])
kana = pool([(0x30A1,0x30FA)])
def arr(name, cps):
    body = ''.join(f"'\\u{{{cp:04X}}}', " + ('\n    ' if i % 8 == 7 else '') for i, cp in enumerate(cps))
    return f"pub const {name}: [char; {len(cps)}] = [\n    {body.rstrip()}\n];\n"
with open(out, 'w') as f:
    f.write(f"// @generated by tools/genpool.py from Unicode confusables.txt ({version or 'see header'}).\n"
            "// Pinned for key format 1: never regenerate in place; a new pool needs a new format version.\n"
            "// Letters confusable with Latin, Greek, Cyrillic or digits are excluded (SPEC §5.1).\n\n")
    f.write(arr('CHEROKEE', cher)); f.write('\n'); f.write(arr('KATAKANA', kana))
print(len(cher), len(kana), len(bad))
